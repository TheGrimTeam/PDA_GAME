// Генератор случайного набора предметов (для квестов на апгрейд)
function genQ(min, max) {
    let jk = Object.keys(ITEMS_DB).filter(k => ITEMS_DB[k].cat === 'junk' || ITEMS_DB[k].cat === 'gear');
    let q = []; let c = Math.floor(Math.random() * (max - min + 1)) + min;
    for (let i = 0; i < c; i++) q.push(jk[Math.floor(Math.random() * jk.length)]);
    return q;
}
